rows, paths = [], []
for name, p in pts.items():
    p = np.array(p, float)
    x, y = ax.data(p[:, 0], p[:, 1])
    f = PchipInterpolator(x, y)
    xx = np.linspace(x[0], x[-1], 160)
    yy = np.clip(f(xx), 0, None)
    rows += [f"{name},{a:.5g},{b:.5g}" for a, b in zip(xx, yy)]
    paths.append(ax.pix(xx, yy))
